const localAssetUrls = {
  'Ethiopian dress.jpeg': new URL('../assets/Ethiopian dress.jpeg', import.meta.url).href,
  'Ethiopian guys.jpeg': new URL('../assets/Ethiopian guys.jpeg', import.meta.url).href,
  'Instagram.jpeg': new URL('../assets/Instagram.jpeg', import.meta.url).href,
  '_ (1).jpeg': new URL('../assets/_ (1).jpeg', import.meta.url).href,
  '_ (2).jpeg': new URL('../assets/_ (2).jpeg', import.meta.url).href,
  '_ (3).jpeg': new URL('../assets/_ (3).jpeg', import.meta.url).href,
  '_.jpeg': new URL('../assets/_.jpeg', import.meta.url).href,
};

function localPhoto(fileName) {
  const asset = localAssetUrls[fileName];

  if (!asset) {
    throw new Error(`Local product image not found: ${fileName}`);
  }

  return asset;
}

