function makeProduct({
  id,
  slug,
  name,
  category,
  price,
  material,
  craftsmanship = 'handmade',
  description,
  photo,
  shop,
  rating = 4.8,
  stock = 8,
  variants,
}) {
  return {
    id,
    slug,
    name,
    category,
    orderable: false,
    price,
    material,
    craftsmanship,
    description,
    images: [localPhoto(photo)],
    shop,
    rating,
    stock,
    variants: variants.map(([label, variantPrice]) => ({
      id: `${id}-${label.toLowerCase().replaceAll(' ', '-')}`,
      label,
      price: variantPrice,
      inStock: true,
    })),
  };
}

